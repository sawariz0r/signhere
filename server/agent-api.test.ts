import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import request from 'supertest';
import { createApp } from './app.js';
import { uid } from './db.js';
import { hashPassword } from './security.js';
import { createDraft, templateBlocks } from '../web/editor/model.js';

const databaseUrl = process.env.TEST_DATABASE_URL;
const origin = 'http://localhost:3000';
test('agent keys isolate credentials, tenants, scopes, revisions and shared saves', { skip: !databaseUrl }, async t => {
  const dataDir = await mkdtemp(join(tmpdir(), 'signhere-agent-'));
  let clock = Date.now();
  const schema = 'agent_' + uid().replaceAll('-', '');
  const runtime = await createApp({ databaseUrl: databaseUrl!, schema, dataDir, baseUrl: origin, setupToken: 'agent-tests-installation-key-long-enough', legacyCreation: true, rateLimit: false, now: () => clock });
  t.after(async () => { await runtime.db.query('DROP SCHEMA "' + schema + '" CASCADE'); await runtime.close(); await rm(dataDir, { recursive: true, force: true }); });
  const owner = request.agent(runtime.app), other = request.agent(runtime.app), guest = request(runtime.app);
  const post = (path: string, data: unknown, agent = owner) => agent.post(path).set('Origin', origin).send(data);
  const setup = await post('/api/setup', { setupToken: 'agent-tests-installation-key-long-enough', name: 'Owner', email: 'agentowner@example.test', password: 'correct horse battery staple', teamName: 'My Team' });
  assert.equal(setup.status, 201, setup.text);
  const team = uid(), user = uid();
  await runtime.db.query('INSERT INTO teams(id,name) VALUES($1,$2)', [team, 'Other Team']);
  await runtime.db.query("INSERT INTO users(id,team_id,name,email,password_hash,role,created_at) VALUES($1,$2,'Other','agentother@example.test',$3,'owner',$4)", [user, team, await hashPassword('other correct horse password'), new Date(clock).toISOString()]);
  assert.equal((await post('/api/login', { email: 'agentother@example.test', password: 'other correct horse password' }, other)).status, 200);
  const scopes = ['drafts:read', 'drafts:write', 'discussion:read', 'discussion:write'];
  const issued = await post('/api/agent-keys', { name: 'Claude', scopes, expiresInDays: 1 });
  assert.equal(issued.status, 201, issued.text);
  const key = issued.body.token;
  assert.match(key, /^shk_[A-Za-z0-9_-]{43}$/);
  assert.equal(issued.body.mcpUrl, origin + '/mcp');
  assert.equal(issued.body.key.lastUsedAt, null);
  const list = await owner.get('/api/agent-keys');
  assert.equal(list.body.keys.length, 1);
  assert.equal(JSON.stringify(list.body).includes(key), false);
  const stored = (await runtime.db.query('SELECT * FROM agent_keys WHERE id=$1', [issued.body.key.id])).rows[0];
  assert.notEqual(stored.token_hash, key);
  assert.equal((await owner.get('/api/v1/workspace')).status, 401, 'cookies never grant agent access');
  assert.equal((await owner.post('/api/agent-keys').send({ name: 'unsafe', scopes })).status, 403, 'key administration retains cookie origin checks');
  assert.equal((await guest.get('/api/v1/workspace').set('Authorization', 'Bearer wrong')).status, 401);
  const api = (method: 'get' | 'post' | 'put', path: string, data?: unknown, apiKey = key) => guest[method]('/api/v1' + path).set('Authorization', 'Bearer ' + apiKey).send(data);
  assert.equal((await guest.post('/api/v1/drafts').set('Authorization', 'Bearer ' + key).set('Origin', 'https://untrusted.example').send({})).status, 403);
  const workspace = await api('get', '/workspace');
  assert.equal(workspace.status, 200, workspace.text);
  assert.equal(workspace.body.workspace.name, 'My Team');
  assert.equal(workspace.body.baseUrl, origin);
  assert.equal((await guest.get('/api/drafts').set('Authorization', 'Bearer ' + key)).status, 401, 'bearer keys cannot enter cookie routes');
  const draft = createDraft('agentdraft000001', setup.body.user);
  draft.title = 'Agent proposal'; draft.blocks = templateBlocks('agreement');
  draft.company = { id: 'client', name: 'Client AB', orgNr: '', address: '', zip: '', city: '', contacts: [{ id: 'client-person', name: 'Client', email: 'client@example.test', role: '', signs: true }] };
  const create = { draft, requestId: uid() };
  const created = await api('post', '/drafts', create);
  assert.equal(created.status, 201, created.text);
  assert.equal(created.body.revision, 1);
  assert.equal(created.body.url, origin + '/editor/' + draft.id);
  assert.deepEqual((await api('post', '/drafts', create)).body, created.body, 'lost response replay returns same result');
  assert.equal((await api('post', '/drafts', { ...create, draft: { ...draft, title: 'Different' } })).status, 409, 'request IDs cannot be reused for different data');
  assert.equal((await api('get', '/drafts')).body.drafts.length, 1);
  const foreignKey = await post('/api/agent-keys', { name: 'Other', scopes }, other);
  assert.equal((await api('get', '/drafts/' + draft.id, undefined, foreignKey.body.token)).status, 404);
  assert.equal((await api('get', '/drafts', undefined, foreignKey.body.token)).body.drafts.length, 0);
  assert.equal((await post('/api/agent-keys/' + issued.body.key.id + '/revoke', {}, other)).status, 404);
  const readKey = await post('/api/agent-keys', { name: 'Read only', scopes: ['drafts:read'] });
  assert.equal((await api('post', '/drafts', { draft, requestId: uid() }, readKey.body.token)).status, 403);
  assert.equal((await api('get', '/drafts/' + draft.id + '/discussion', undefined, readKey.body.token)).status, 403);
  const update = { draft: { ...draft, title: 'Updated proposal' }, expectedRevision: 1, requestId: uid() };
  const updated = await api('put', '/drafts/' + draft.id, update);
  assert.equal(updated.body.revision, 2, updated.text);
  const conflict = await api('put', '/drafts/' + draft.id, { ...update, requestId: uid() });
  assert.equal(conflict.status, 409);
  assert.equal(conflict.body.currentRevision, 2);
  assert.equal((await api('get', '/drafts/' + draft.id)).body.draft.title, 'Updated proposal');
  const save = { expectedRevision: 2, requestId: uid() };
  const privateSaved = await api('post', '/drafts/' + draft.id + '/save', save);
  assert.equal(privateSaved.body.version, 1);
  assert.equal(privateSaved.body.visibility, 'private');
  assert.equal((await api('post', '/drafts/' + draft.id + '/save', save)).body.version, 1);
  const comment = { version: 1, blockId: draft.blocks[0].id, body: 'Clarify scope', requestId: uid() };
  const commented = await api('post', '/drafts/' + draft.id + '/comments', comment);
  assert.equal(commented.status, 200, commented.text);
  assert.equal((await api('get', '/drafts/' + draft.id + '/discussion')).body.threads[0].comments[0].body, 'Clarify scope');
  assert.equal((await api('post', '/drafts/' + draft.id + '/comments', comment)).body.id, commented.body.id);
  const link = await post('/api/drafts/' + draft.id + '/links', { contactId: 'client-person', revision: 2 });
  assert.equal(link.status, 201, link.text);
  assert.equal((await api('put', '/drafts/' + draft.id, { ...update, expectedRevision: 2, requestId: uid(), draft: { ...update.draft, title: 'Private agent revision' } })).body.revision, 3);
  assert.equal((await api('post', '/drafts/' + draft.id + '/save', { expectedRevision: 3, requestId: uid() })).status, 409, 'shared saves require explicit opt-in');
  assert.equal((await api('post', '/drafts/' + draft.id + '/save', { expectedRevision: 3, requestId: uid(), allowSharedUpdate: true })).status, 403, 'shared saves also require separate scope');
  const shareKey = await post('/api/agent-keys', { name: 'Share updates', scopes: [...scopes, 'reviews:share'] });
  assert.equal((await api('post', '/drafts/' + draft.id + '/save', { expectedRevision: 3, requestId: uid() }, shareKey.body.token)).status, 409);
  const sharedSaved = await api('post', '/drafts/' + draft.id + '/save', { expectedRevision: 3, requestId: uid(), allowSharedUpdate: true }, shareKey.body.token);
  assert.equal(sharedSaved.body.version, 2);
  assert.equal(sharedSaved.body.shared, true);
  assert.equal(sharedSaved.body.visibility, 'shared');
  const token = new URL(link.body.url).hash.slice(1);
  assert.equal((await post('/api/review/session', { token }, guest)).body.draft.title, 'Private agent revision');
  const replied = await api('post', '/drafts/' + draft.id + '/comments', { version: 0, threadId: commented.body.threadId, body: 'Reply to existing context', requestId: uid() });
  assert.equal(replied.status, 200, replied.text);
  assert.equal((await api('post', '/drafts/' + draft.id + '/comments', { version: 0, body: 'Cannot create unbound thread', requestId: uid() })).status, 400);
  const raceDraft = { ...draft, id: 'agentracedraft001' };
  assert.equal((await api('post', '/drafts', { draft: raceDraft, requestId: uid() })).status, 201);
  const race = await Promise.all(['First', 'Second'].map(title => api('put', '/drafts/' + raceDraft.id, { expectedRevision: 1, requestId: uid(), draft: { ...raceDraft, title } })));
  assert.deepEqual(race.map(response => response.status).sort(), [200, 409], 'concurrent edits cannot overwrite each other');
  const audits = (await runtime.db.query('SELECT * FROM agent_audit')).rows;
  assert.ok(audits.length >= 4);
  assert.ok(audits.some(row => row.outcome === 'http_403'));
  assert.ok(audits.some(row => row.operation === 'key.created'));
  await assert.rejects(runtime.db.query("UPDATE agent_audit SET outcome='success'"), /append-only/);
  assert.equal(JSON.stringify(audits).includes('Clarify scope'), false);
  assert.equal(JSON.stringify(audits).includes(key), false);
  assert.equal((await post('/api/agent-keys/' + issued.body.key.id + '/revoke', {})).status, 200);
  assert.equal((await api('get', '/workspace')).status, 401);
  const expiring = await post('/api/agent-keys', { name: 'Short lived', scopes: ['drafts:read'], expiresInDays: 1 });
  assert.equal(expiring.status, 201, expiring.text);
  clock += 86400000;
  assert.equal((await api('get', '/workspace', undefined, readKey.body.token)).status, 200, 'default 90-day key remains valid');
  assert.equal((await api('get', '/workspace', undefined, expiring.body.token)).status, 401);
});
