import test from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import request from 'supertest';
import { createApp } from './app.js';
import { uid } from './db.js';
import { token } from './security.js';
import { chatGPTClientId, validateChatGPTClient } from './oauth-client.js';
const databaseUrl = process.env.TEST_DATABASE_URL;
const origin = 'http://localhost:3000';
const clientId = 'https://chatgpt.com/oauth/client.json';
const callback = 'https://chatgpt.com/connector_platform_oauth_redirect';
const client = { client_id: clientId, redirect_uris: [callback], token_endpoint_auth_method: 'private_key_jwt', token_endpoint_auth_methods_supported: ['none', 'private_key_jwt'], grant_types: ['authorization_code', 'refresh_token'], response_types: ['code'], client_name: 'ChatGPT' };
test('CIMD accepts actual public-client metadata, validates exact callback and blocks arbitrary origins', async () => {
  assert.equal((await validateChatGPTClient(clientId, callback, async () => client)).name, 'ChatGPT');
  for (const id of ['http://chatgpt.com/oauth/client.json', 'https://chatgpt.com.evil.test/oauth/client.json', 'https://127.0.0.1/oauth/client.json', 'https://chatgpt.com:443/oauth/client.json', 'https://chatgpt.com/oauth/client.json?url=evil', 'https://chatgpt.com/oauth/client.json#x', 'https://chatgpt.com/oauth/../client.json']) assert.throws(() => chatGPTClientId(id));
  await assert.rejects(validateChatGPTClient(clientId, callback + '/other', async () => client));
  await assert.rejects(validateChatGPTClient(clientId, callback, async () => ({ ...client, client_id: 'another' })));
  await assert.rejects(validateChatGPTClient(clientId, callback, async () => ({ ...client, token_endpoint_auth_methods_supported: ['private_key_jwt'] })));
  assert.equal(chatGPTClientId('https://chatgpt.com/oauth/callback_123/client.json'), 'https://chatgpt.com/oauth/callback_123/client.json');
});
test('built-in OAuth binds browser, login, client, resource, redirect and PKCE; grants expire and revoke', { skip: !databaseUrl }, async t => {
  const dataDir = await mkdtemp(join(tmpdir(), 'signhere-oauth-'));
  const schema = 'oauth_' + uid().replaceAll('-', '');
  let clock = Date.now();
  const runtime = await createApp({ databaseUrl: databaseUrl!, schema, dataDir, baseUrl: origin, setupToken: 'oauth-tests-installation-key-long-enough', legacyCreation: true, rateLimit: false, now: () => clock, oauth: { metadataLoader: async () => client } });
  t.after(async () => { await runtime.db.query('DROP SCHEMA "' + schema + '" CASCADE'); await runtime.close(); await rm(dataDir, { recursive: true, force: true }); });
  const owner = request.agent(runtime.app), otherBrowser = request.agent(runtime.app), guest = request(runtime.app);
  const post = (path: string, body: unknown, agent = owner) => agent.post(path).set('Origin', origin).send(body);
  const setup = await post('/api/setup', { setupToken: 'oauth-tests-installation-key-long-enough', name: 'Owner', email: 'owner@example.test', password: 'correct horse battery staple', teamName: 'OAuth team' });
  assert.equal(setup.status, 201, setup.text);
  const meta = await guest.get('/.well-known/oauth-authorization-server');
  assert.equal(meta.status, 200); assert.deepEqual(meta.body.token_endpoint_auth_methods_supported, ['none']);
  assert.equal(meta.body.registration_endpoint, undefined); assert.equal(meta.body.authorization_response_iss_parameter_supported, true);
  assert.deepEqual(meta.body.grant_types_supported, ['authorization_code']);
  const resource = origin + '/mcp/oauth';
  assert.equal((await guest.get('/.well-known/oauth-protected-resource/mcp/oauth')).body.resource, resource);
  const verifier = token();
  const challenge = createHash('sha256').update(verifier).digest('base64url');
  const authorizeInput = { response_type: 'code', client_id: clientId, redirect_uri: callback, resource, state: token(), code_challenge: challenge, code_challenge_method: 'S256' };
  async function start(query: object = {}) {
    const started = await owner.get('/oauth/authorize').query({ ...authorizeInput, ...query });
    assert.equal(started.status, 302, started.text);
    const pending = new URL(started.headers.location).searchParams.get('request')!;
    return { pending, details: '/api/oauth/authorization/' + pending };
  }
  const pending = await start({ prompt: 'consent' });
  assert.equal((await owner.get(pending.details)).status, 200);
  assert.equal((await post(pending.details, { approved: true, expiresInMinutes: 60 }, otherBrowser)).status, 401);
  assert.equal((await post('/api/login', { email: 'owner@example.test', password: 'correct horse battery staple' }, otherBrowser)).status, 200);
  assert.equal((await otherBrowser.get(pending.details)).status, 403, 'even the same user cannot steal another browser pending request');
  const details = await owner.get(pending.details);
  assert.equal(details.body.expiresInMinutes, 90 * 24 * 60);
  assert.deepEqual(details.body.scopes, ['drafts:read', 'drafts:write', 'discussion:read', 'discussion:write']);
  assert.equal(details.body.client.name, 'ChatGPT'); assert.equal(details.body.workspace.name, 'OAuth team');
  assert.equal((await owner.post(pending.details).send({ approved: true })).status, 403, 'consent needs same-origin JSON');
  const approved = await post(pending.details, { approved: true, expiresInMinutes: 15 });
  assert.equal(approved.status, 200, approved.text);
  const authorized = new URL(approved.body.redirectUrl);
  assert.equal(authorized.origin, 'https://chatgpt.com'); assert.equal(authorized.searchParams.get('iss'), origin); assert.equal(authorized.searchParams.get('state'), authorizeInput.state);
  const code = authorized.searchParams.get('code')!;
  assert.ok(code);
  assert.equal((await post(pending.details, { approved: true, expiresInMinutes: 15 })).status, 404, 'consent is single use');
  const exchange = (authorizationCode: string, overrides: object = {}) => guest.post('/oauth/token').type('form').send({ grant_type: 'authorization_code', client_id: clientId, redirect_uri: callback, resource, code: authorizationCode, code_verifier: verifier, ...overrides });
  assert.equal((await exchange(code, { resource: origin + '/mcp' })).status, 400, 'wrong resource cannot redeem');
  assert.equal((await exchange(code, { redirect_uri: callback + '/other' })).status, 400, 'wrong redirect cannot redeem');
  assert.equal((await exchange(code, { client_id: 'https://chatgpt.com/oauth/other/client.json' })).status, 400, 'wrong client cannot redeem');
  const race = await Promise.all([exchange(code), exchange(code)]);
  assert.deepEqual(race.map(response => response.status).sort(), [200, 400], 'concurrent exchanges issue exactly one token');
  const issued = race.find(response => response.status === 200)!;
  assert.equal(issued.status, 200, issued.text); assert.match(issued.body.access_token, /^sho_[\w-]{43}$/);
  assert.equal(issued.body.expires_in, 900); assert.equal(issued.body.refresh_token, undefined);
  assert.equal((await exchange(code)).status, 400, 'authorization code is single-use');
  const bearer = issued.body.access_token;
  const connections = await owner.get('/api/oauth/connections');
  assert.equal(connections.body.connections.length, 1); assert.equal(connections.body.mcpUrl, resource);
  assert.equal((await owner.get('/api/agent-keys')).body.keys.length, 0, 'OAuth grants never appear as manually copied API keys');
  assert.equal(JSON.stringify(connections.body).includes(bearer), false);
  assert.equal((await guest.get('/api/v1/workspace').set('Authorization', 'Bearer ' + bearer)).status, 401);
  assert.equal((await guest.post('/mcp').set('Host', 'localhost:3000').set('Authorization', 'Bearer ' + bearer).send({})).status, 401);
  const invoke = () => guest.post('/mcp/oauth').set('Host', 'localhost:3000').set('Authorization', 'Bearer ' + bearer).set('Accept', 'application/json, text/event-stream').send({ jsonrpc: '2.0', id: 1, method: 'tools/call', params: { name: 'signhere_workspace', arguments: {} } });
  const workspace = await invoke();
  assert.equal(workspace.status, 200, workspace.text);
  assert.ok(workspace.text.includes('OAuth team'), workspace.text);
  assert.equal((await guest.get('/mcp/oauth').set('Host', 'localhost:3000')).headers['www-authenticate'].includes('resource_metadata='), true);
  assert.equal((await post('/api/oauth/connections/' + connections.body.connections[0].id + '/revoke', {})).status, 200);
  assert.equal((await invoke()).status, 401);
  const deniedPending = await start({ scope: 'drafts:read' });
  await owner.get(deniedPending.details);
  const denied = await post(deniedPending.details, { approved: false });
  const deniedUrl = new URL(denied.body.redirectUrl);
  assert.equal(deniedUrl.searchParams.get('error'), 'access_denied'); assert.equal(deniedUrl.searchParams.get('iss'), origin);
  const badVerifierPending = await start(); await owner.get(badVerifierPending.details);
  const badVerifierApproval = await post(badVerifierPending.details, { approved: true });
  const badCode = new URL(badVerifierApproval.body.redirectUrl).searchParams.get('code')!;
  assert.equal((await exchange(badCode, { code_verifier: token() })).status, 400);
  assert.equal((await exchange(badCode)).status, 400, 'library intentionally consumes code after a wrong verifier');
  const faultPending = await start(); await owner.get(faultPending.details);
  const faultApproval = await post(faultPending.details, { approved: true });
  const faultCode = new URL(faultApproval.body.redirectUrl).searchParams.get('code')!;
  await runtime.db.query("CREATE FUNCTION reject_oauth_token() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'test token storage fault'; END $$; CREATE TRIGGER reject_oauth_token BEFORE INSERT ON oauth_access_tokens FOR EACH ROW EXECUTE FUNCTION reject_oauth_token()");
  assert.equal((await exchange(faultCode)).status, 500, 'storage failures are server errors');
  await runtime.db.query('DROP TRIGGER reject_oauth_token ON oauth_access_tokens; DROP FUNCTION reject_oauth_token()');
  assert.equal((await exchange(faultCode)).status, 200, 'a storage failure rolls back code consumption and permits a safe retry');
  const sessionPending = await start(); await owner.get(sessionPending.details);
  assert.equal((await post('/api/logout', {})).status, 200);
  assert.equal((await post('/api/login', { email: 'owner@example.test', password: 'correct horse battery staple' })).status, 200);
  assert.equal((await post(sessionPending.details, { approved: true })).status, 403, 'a fresh session cannot approve an earlier bound request');
  const expiresPending = await start(); await owner.get(expiresPending.details);
  const expiresApproval = await post(expiresPending.details, { approved: true, expiresInMinutes: 15 });
  const expiring = await exchange(new URL(expiresApproval.body.redirectUrl).searchParams.get('code')!);
  assert.equal(expiring.status, 200, expiring.text);
  clock += 15 * 60000;
  assert.equal((await guest.get('/mcp/oauth').set('Host', 'localhost:3000').set('Authorization', 'Bearer ' + expiring.body.access_token)).status, 401);
  assert.equal((await guest.post('/oauth/token').type('form').send({ grant_type: 'refresh_token', refresh_token: bearer, client_id: clientId })).status, 400);
  for (const duration of [undefined, 365 * 24 * 60]) {
    assert.equal((await post('/api/login', { email: 'owner@example.test', password: 'correct horse battery staple' })).status, 200);
    const longPending = await start(); assert.equal((await owner.get(longPending.details)).status, 200);
    assert.equal((await post(longPending.details, { approved: true, expiresInMinutes: 365 * 24 * 60 + 1 })).status, 400, 'OAuth access is capped at one year');
    const longApproval = await post(longPending.details, { approved: true, ...(duration === undefined ? {} : { expiresInMinutes: duration }) });
    assert.equal(longApproval.status, 200, longApproval.text);
    const longIssued = await exchange(new URL(longApproval.body.redirectUrl).searchParams.get('code')!);
    assert.equal(longIssued.status, 200, longIssued.text);
    const lifetimeMinutes = duration ?? 90 * 24 * 60;
    assert.equal(longIssued.body.expires_in, lifetimeMinutes * 60);
    assert.equal(longIssued.body.refresh_token, undefined);
    const longInvoke = () => guest.post('/mcp/oauth').set('Host', 'localhost:3000').set('Authorization', 'Bearer ' + longIssued.body.access_token).set('Accept', 'application/json, text/event-stream').send({ jsonrpc: '2.0', id: 2, method: 'tools/call', params: { name: 'signhere_workspace', arguments: {} } });
    clock += 24 * 60 * 60000;
    assert.equal((await longInvoke()).status, 200, 'approved connections still work after the former 24-hour cap');
    clock += (lifetimeMinutes - 24 * 60) * 60000;
    assert.equal((await longInvoke()).status, 401, 'long-lived connections expire at the approved deadline');
  }
  const rows = (await runtime.db.query('SELECT * FROM oauth_codes LIMIT 1')).rows;
  assert.ok(rows.length); assert.equal(JSON.stringify(rows).includes(code), false);
  const audit = (await runtime.db.query('SELECT * FROM agent_audit')).rows;
  assert.ok(audit.some(row => row.operation === 'oauth.authorized'));
  assert.equal(JSON.stringify(audit).includes(bearer), false);
});
