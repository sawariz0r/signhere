const databaseUrl = process.env.TEST_DATABASE_URL;
const origin = 'http://localhost:3000';
test('private review keeps working copies private, preserves discussion across revisions and restricts capabilities', { skip: !databaseUrl }, async t => {
  const dataDir = await mkdtemp(join(tmpdir(), 'signhere-reviews-'));
  let clock = Date.now();
  const schema = 'review_' + uid().replaceAll('-', '');
  const runtime = await createApp({ databaseUrl: databaseUrl!, schema, dataDir, baseUrl: origin, setupToken: 'review-tests-installation-key-long-enough', legacyCreation: true, rateLimit: false, now: () => clock });
  t.after(async () => { await runtime.db.query('DROP SCHEMA "' + schema + '" CASCADE'); await runtime.close(); await rm(dataDir, { recursive: true, force: true }); });
  const owner = request.agent(runtime.app), guest = request(runtime.app), stranger = request.agent(runtime.app);
  const post = (path: string, data: unknown, agent: any = owner) => agent.post(path).set('Origin', origin).send(data);
  const setup = await post('/api/setup', { setupToken: 'review-tests-installation-key-long-enough', name: 'Owner', email: 'owner@example.test', password: 'correct horse battery staple', teamName: 'My Team' });
  assert.equal(setup.status, 201, setup.text);
  const team = uid(), user = uid();
  await runtime.db.query('INSERT INTO teams(id,name) VALUES($1,$2)', [team, 'Another Team']);
  await runtime.db.query("INSERT INTO users(id,team_id,name,email,password_hash,role,created_at) VALUES($1,$2,'Other','other@example.test',$3,'owner',$4)", [user, team, await hashPassword('other correct horse password'), new Date(clock).toISOString()]);
  assert.equal((await post('/api/login', { email: 'other@example.test', password: 'other correct horse password' }, stranger)).status, 200);
  const draft = createDraft('reviewdraft000001', setup.body.user);
  draft.title = 'Shared proposal'; draft.blocks = templateBlocks('agreement');
  draft.fields['private.unused'] = 'never share this unused field';
  draft.company = { id: 'company', name: 'Client AB', orgNr: '', address: '', zip: '', city: '', contacts: [{ id: 'a', name: 'Client', email: 'client@example.test', role: '', signs: true }, { id: 'b', name: 'Hidden', email: 'hidden@example.test', role: '', signs: false }] };
  const save = (content: any, expectedRevision: number, agent: any = owner) => agent.put('/api/drafts/' + draft.id).set('Origin', origin).send({ draft: content, expectedRevision });
  assert.equal((await save(draft, 0, guest)).status, 401);
  assert.equal((await save(draft, 0)).body.revision, 1);
  assert.equal((await save(draft, 0)).body.revision, 1, 'a lost save response can be retried');
  const unsafe = structuredClone(draft);
  unsafe.blocks = [{ id: 'unsafe', type: 'image', src: 'https://tracker.example.test/pixel.png', caption: '', width: 'wide', ratio: '' }];
  assert.equal((await save(unsafe, 1)).status, 400, 'external asset URLs are not accepted into private drafts');
  const unsafeLink = structuredClone(draft);
  unsafeLink.blocks = [{ id: 'unsafe-link', type: 'text', title: '', content: { type: 'doc', content: [{ type: 'paragraph', content: [{ type: 'text', text: 'Link', marks: [{ type: 'link', attrs: { href: 'javascript:alert(1)' } }] }] }] } }];
  assert.equal((await save(unsafeLink, 1)).status, 400, 'unsafe link schemes are rejected before publication');
  assert.equal((await owner.get('/api/drafts/' + draft.id)).body.revision, 1);
  assert.equal((await stranger.get('/api/drafts/' + draft.id)).status, 404);
  assert.equal((await save(draft, 0, stranger)).status, 409);
  assert.equal((await stranger.get('/api/drafts')).body.drafts.length, 0);
  assert.equal((await post(`/api/drafts/${draft.id}/publish`, { revision: 1 })).body.version, 1);
  assert.equal((await post(`/api/drafts/${draft.id}/publish`, { revision: 1 })).body.version, 1);
  const link = await post(`/api/drafts/${draft.id}/links`, { name: 'Client', days: 1 });
  assert.equal(link.status, 201, link.text);
  const token = new URL(link.body.url).hash.slice(1);
  const session = () => post('/api/review/session', { token }, guest);
  let shared = await session();
  assert.equal(shared.status, 200, shared.text);
  assert.equal(shared.body.draft.title, 'Shared proposal');
  assert.ok(shared.body.draft.frozenAt);
  assert.equal(shared.body.draft.fields['private.unused'], undefined);
  assert.equal(shared.body.draft.company.contacts.length, 1);
  assert.equal((await post('/api/sign/session', { token }, guest)).status, 404);
  assert.equal((await guest.get('/api/drafts/' + draft.id)).status, 401);
  const body = { token, version: 1, blockId: draft.blocks[0].id, body: 'Can we revise the scope?', requestId: uid() };
  const comment = await post('/api/review/comments', body, guest);
  assert.equal(comment.status, 200, comment.text);
  assert.equal((await post('/api/review/comments', body, guest)).body.id, comment.body.id);
  assert.equal((await post('/api/review/comments', { ...body, body: 'different' }, guest)).status, 409);
  assert.equal((await post('/api/review/comments', { ...body, requestId: uid(), version: 2 }, guest)).status, 409);
  assert.equal((await post(`/api/drafts/${draft.id}/comments`, { version: 1, threadId: comment.body.threadId, body: 'Yes, revising now.', requestId: uid() })).status, 200);
  assert.equal((await post(`/api/drafts/${draft.id}/threads/${comment.body.threadId}`, { resolved: true }, stranger)).status, 404);
  assert.equal((await post(`/api/drafts/${draft.id}/threads/${comment.body.threadId}`, { resolved: true })).status, 200);
  assert.equal((await post('/api/review/comments', { token, version: 1, threadId: comment.body.threadId, body: 'One more thing', requestId: uid() }, guest)).status, 409);
  assert.equal((await post(`/api/drafts/${draft.id}/threads/${comment.body.threadId}`, { resolved: false })).status, 200);
  const updated = { ...draft, title: 'Unshared edits', blocks: draft.blocks.slice(1), updatedAt: new Date(clock + 1).toISOString() };
  const race = await Promise.all([save(updated, 1), save({ ...updated, title: 'Competing tab' }, 1)]);
  assert.deepEqual(race.map(result => result.status).sort(), [200, 409]);
  shared = await session(); assert.equal(shared.body.draft.title, 'Shared proposal');
  const current = (await owner.get('/api/drafts/' + draft.id)).body;
  assert.equal(current.threads[0].comments.length, 2);
  assert.equal((await post(`/api/drafts/${draft.id}/publish`, { revision: current.revision })).body.version, 2);
  shared = await session(); assert.equal(shared.body.version, 2); assert.equal(shared.body.draft.title, current.draft.title);
  assert.equal((await post('/api/review/comments', body, guest)).body.id, comment.body.id, 'a prior accepted comment remains retryable after publication changes');
  const old = await post('/api/review/session', { token, version: 1 }, guest);
  assert.equal(old.body.draft.title, 'Shared proposal'); assert.equal(old.body.threads[0].blockId, body.blockId);
  assert.equal((await post('/api/review/comments', { ...body, requestId: uid(), version: 2 }, guest)).status, shared.body.draft.blocks.some((block: any) => block.id === body.blockId) ? 200 : 404);
  await assert.rejects(runtime.db.query('UPDATE review_versions SET published_at=$1 WHERE draft_id=$2', ['changed', draft.id]), /append-only/);
  const pdf = await PDFDocument.create(); pdf.addPage().drawText('Final agreement');
  const signingBody = { title: 'Final agreement', fileName: 'final.pdf', pdfBase64: Buffer.from(await pdf.save()).toString('base64'), recipients: [{ name: 'Client', email: 'client@example.test' }], methodId: 'draw', draftSource: { id: draft.id, revision: current.revision } };
  const signed = await post('/api/documents', signingBody);
  assert.equal(signed.status, 201, signed.text);
  const retry = await post('/api/documents', signingBody);
  assert.equal(retry.status, 201, retry.text); assert.equal(retry.body.document.id, signed.body.document.id); assert.equal(retry.body.alreadyCreated, true);
  const signingToken = new URL(signed.body.links[0].url).hash.slice(1);
  const discussion = await post('/api/sign/discussion', { token: signingToken }, guest);
  assert.equal(discussion.status, 200, discussion.text);
  assert.equal(discussion.body.threads[0].comments.length, 2, 'the signing capability sees prior review discussion');
  assert.equal(discussion.body.source.fields['private.unused'], undefined);
  assert.equal((await session()).body.signing.state, 'pending');
  assert.equal((await post('/api/review/comments', { ...body, requestId: uid() }, guest)).status, 409, 'review comments close when signing starts');
  assert.equal((await post('/api/sign/comments', { token, body: 'Review link must not authorize signing discussion', requestId: uid() }, guest)).status, 404);
  const signingComment = await post('/api/sign/comments', { token: signingToken, body: 'Question about the exact signing copy', requestId: uid() }, guest);
  assert.equal(signingComment.status, 200, signingComment.text);
  assert.ok(!(await session()).body.threads.some((thread: any) => thread.id === signingComment.body.threadId), 'signing discussion is not exposed through older review-only capabilities');
  const reply = { version: 0, threadId: signingComment.body.threadId, body: 'Reply on the signing copy', requestId: uid() };
  assert.equal((await post(`/api/drafts/${draft.id}/comments`, reply)).status, 200);
  assert.equal((await post(`/api/drafts/${draft.id}/comments`, reply)).status, 200, 'owner replies to signing discussion are retryable');
  assert.equal((await post('/api/sign/discussion', { token: signingToken }, guest)).body.threads.find((thread: any) => thread.id === signingComment.body.threadId).comments.length, 2);
  const future = { ...current.draft, title: 'Future private content' };
  assert.equal((await save(future, current.revision)).status, 200);
  await post(`/api/drafts/${draft.id}/publish`, { revision: current.revision + 1 });
  assert.equal((await post('/api/sign/discussion', { token: signingToken }, guest)).body.versions.length, 2, 'a signing capability cannot see future draft revisions');
  assert.equal((await post('/api/sign/review-version', { token: signingToken, version: 3 }, guest)).status, 404);
  assert.equal((await post('/api/sign/review-version', { token: signingToken, version: 1 }, guest)).body.draft.title, 'Shared proposal');
  assert.equal((await owner.get('/api/drafts/' + draft.id)).body.draft.title, future.title);
  assert.equal((await post('/api/documents', signingBody, stranger)).status, 404);
  clock += 86400001; assert.equal((await session()).status, 404);
  assert.equal((await post('/api/login', { email: 'owner@example.test', password: 'correct horse battery staple' })).status, 200);
  const replacement = await post(`/api/drafts/${draft.id}/links`, { name: 'Client' });
  const replacementToken = new URL(replacement.body.url).hash.slice(1);
  assert.equal((await post('/api/review/session', { token: replacementToken }, guest)).status, 200);
  await post(`/api/drafts/${draft.id}/links/${replacement.body.id}/revoke`, {});
  assert.equal((await post('/api/review/session', { token: replacementToken }, guest)).status, 404);
  assert.equal((await post('/api/review/comments', { ...body, token: replacementToken, requestId: uid() }, guest)).status, 404);
});

test('draft and review migration works with separate restricted runtime and migration roles', { skip: !databaseUrl }, async t => {
  const suffix = uid().replaceAll('-', '');
  const dbName = 'review_roles_' + suffix, migrationRole = 'review_m_' + suffix, runtimeRole = 'review_r_' + suffix;
  const admin = new pg.Pool({ connectionString: databaseUrl });
  const password = 'disposable-test-password-' + suffix;
  const dataDir = await mkdtemp(join(tmpdir(), 'signhere-review-roles-'));
  let runtime: Awaited<ReturnType<typeof createApp>> | undefined;
  t.after(async () => {
    await runtime?.close();
    await admin.query(`DROP DATABASE IF EXISTS "${dbName}" WITH (FORCE)`);
    await admin.query(`DROP ROLE IF EXISTS "${runtimeRole}"`);
    await admin.query(`DROP ROLE IF EXISTS "${migrationRole}"`);
    await admin.end(); await rm(dataDir, { recursive: true, force: true });
  });
  await admin.query(`CREATE ROLE "${migrationRole}" LOGIN PASSWORD '${password}'`);
  await admin.query(`CREATE ROLE "${runtimeRole}" LOGIN PASSWORD '${password}'`);
  await admin.query(`CREATE DATABASE "${dbName}" OWNER "${migrationRole}"`);
  const dbUrl = new URL(databaseUrl!); dbUrl.pathname = '/' + dbName;
  const bootstrap = new pg.Pool({ connectionString: dbUrl.href });
  try {
    await bootstrap.query(`REVOKE ALL ON SCHEMA public FROM PUBLIC; GRANT USAGE ON SCHEMA public TO "${runtimeRole}";
      ALTER DEFAULT PRIVILEGES FOR ROLE "${migrationRole}" IN SCHEMA public GRANT SELECT,INSERT,UPDATE,DELETE ON TABLES TO "${runtimeRole}";
      ALTER DEFAULT PRIVILEGES FOR ROLE "${migrationRole}" IN SCHEMA public GRANT USAGE,SELECT ON SEQUENCES TO "${runtimeRole}"`);
  } finally { await bootstrap.end(); }
  dbUrl.username = runtimeRole; dbUrl.password = password;
  const migrationUrl = new URL(dbUrl.href); migrationUrl.username = migrationRole;
  runtime = await createApp({ databaseUrl: dbUrl.href, migrationDatabaseUrl: migrationUrl.href, dataDir, baseUrl: origin, setupToken: 'review-roles-setup-key-long-enough', legacyCreation: true, rateLimit: false });
  const owner = request.agent(runtime.app);
  const setup = await owner.post('/api/setup').set('Origin', origin).send({ setupToken: 'review-roles-setup-key-long-enough', name: 'Owner', email: 'owner@example.test', password: 'correct horse battery staple', teamName: 'Restricted roles' });
  assert.equal(setup.status, 201, setup.text);
  const draft = createDraft('restricted000001', setup.body.user); draft.title = 'Role check'; draft.blocks = templateBlocks('blank');
  const save = await owner.put('/api/drafts/' + draft.id).set('Origin', origin).send({ draft, expectedRevision: 0 });
  assert.equal(save.status, 200, save.text);
  const publish = await owner.post(`/api/drafts/${draft.id}/publish`).set('Origin', origin).send({ revision: 1 });
  assert.equal(publish.status, 200, publish.text);
  await assert.rejects(runtime.db.query('ALTER TABLE review_versions DISABLE TRIGGER ALL'), { code: '42501' });
  await assert.rejects(runtime.db.query('UPDATE review_versions SET published_at=$1', ['changed']), /append-only/);
});
