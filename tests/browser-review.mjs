import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { randomBytes } from 'node:crypto';
import { mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { chromium, expect } from '@playwright/test';
import { createApp } from '../dist/server/app.js';
import { PDFDocument } from 'mupdf';

const databaseUrl = process.env.TEST_DATABASE_URL;
if (!databaseUrl) throw new Error('Set TEST_DATABASE_URL to a disposable PostgreSQL database.');
const schema = 'review_browser_' + randomBytes(8).toString('hex');
const output = resolve('.test-artifacts/browser-review');
await mkdir(output, { recursive: true });
const server = createServer();
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const baseURL = `http://127.0.0.1:${server.address().port}`;
const setupToken = randomBytes(32).toString('base64url');
const runtime = await createApp({ databaseUrl, schema, dataDir: output, baseUrl: baseURL, setupToken, legacyCreation: true, rateLimit: false });
server.on('request', runtime.app);
const browser = await chromium.launch({ headless: true });
const errors = [];
let ownerPage, clientPage;
try {
  const owner = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const client = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const api = owner.request;
  const setup = await api.post(baseURL + '/api/setup', { headers: { Origin: baseURL }, data: { setupToken, name: 'Sara Sender', email: 'sara@example.test', password: 'correct horse battery staple', teamName: 'PRPL' } });
  assert.equal(setup.status(), 201);
  const page = ownerPage = await owner.newPage(), review = clientPage = await client.newPage();
  for (const tab of [page, review]) tab.on('pageerror', error => errors.push(error.stack));
  await page.goto(baseURL);
  await page.getByRole('button', { name: 'Skapa i editorn' }).click();
  await page.getByRole('button', { name: /Tomt dokument/ }).click();
  await page.getByLabel('Dokumentnamn').fill('Serviceoffert');
  await page.locator('.ProseMirror').first().click();
  await page.keyboard.type('Vi levererar en ny webbplats.');
  const id = new URL(page.url()).pathname.split('/')[2];
  const saved = async () => (await (await api.get(`${baseURL}/api/drafts/${id}?optional=1`)).json());
  await expect.poll(async () => JSON.stringify(await saved())).toContain('en ny webbplats');
  await page.reload();
  await expect(page.locator('.ProseMirror').first()).toContainText('en ny webbplats');
  await page.getByRole('button', { name: 'Dela för granskning', exact: true }).click();
  const panel = page.getByRole('complementary', { name: 'Utskick och inställningar' });
  await panel.getByLabel('Klientens namn').fill('Anna Client');
  await panel.getByRole('button', { name: 'Skapa privat länk' }).click();
  const link = await panel.getByRole('textbox', { name: 'Personlig länk' }).inputValue();
  await review.goto(link);
  await expect(review.getByRole('heading', { name: 'Serviceoffert' })).toBeVisible();
  await expect(review.locator('.rd-review-paper')).toContainText('en ny webbplats');
  await review.screenshot({ path: output + '/01-client-document.png', fullPage: true });
  await review.getByRole('button', { name: /^Kommentera avsnitt 1:/ }).click();
  const sheet = review.getByRole('dialog', { name: 'Kommentarer', exact: true });
  await sheet.getByRole('textbox').fill('Kan vi lägga till löpande support?');
  await sheet.getByRole('button', { name: 'Skicka kommentar', exact: true }).click();
  await expect(sheet.locator('.rd-thread')).toContainText('Kan vi lägga till löpande support?');
  await review.screenshot({ path: output + '/02-client-comments.png', fullPage: true });
  assert.equal(await review.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Mobile document does not overflow horizontally');
  await panel.getByRole('button', { name: 'Uppdatera kommentarer' }).click();
  await expect(panel.locator('.rd-thread')).toContainText('Kan vi lägga till löpande support?');
  await panel.locator('.rd-thread').getByRole('button', { name: 'Svara', exact: true }).click();
  await panel.getByRole('textbox', { name: 'Svara', exact: true }).fill('Ja, det lägger jag till i nästa version.');
  await panel.locator('.rd-thread').getByRole('button', { name: 'Skicka kommentar' }).click();
  await expect(panel.locator('.rd-thread')).toContainText('Ja, det lägger jag till');
  await panel.getByRole('button', { name: 'Markera som löst' }).click();
  await expect(panel.locator('.rd-thread')).toContainText('Löst');
  await page.locator('.ProseMirror').first().click();
  await page.keyboard.press('ControlOrMeta+End');
  await page.keyboard.type(' Support ingår under hela året.');
  await expect.poll(async () => JSON.stringify(await saved())).toContain('Support ingår');
  await expect(page.getByText('Ändrat sedan version 1', { exact: true })).toBeVisible();
  await review.reload();
  await expect(review.locator('.rd-review-paper')).not.toContainText('Support ingår');
  await page.getByRole('button', { name: 'Dela version 2', exact: true }).click();
  await expect(panel.getByText(/Version 2 är delad/)).toBeVisible();
  await expect(page.locator('.rd-private-change')).toHaveCount(0, { timeout: 10000 });
  await review.reload();
  await expect(review.locator('.rd-review-paper')).toContainText('Support ingår under hela året.');
  await review.getByLabel('Delad version').selectOption('1');
  await review.getByRole('button', { name: /^Kommentarer/ }).click();
  await expect(sheet.locator('.rd-thread')).toContainText('Ja, det lägger jag till');
  await expect(sheet.getByRole('textbox')).toHaveCount(0);
  await sheet.getByRole('button', { name: 'Stäng kommentarer' }).click();
  await review.getByLabel('Delad version').selectOption('');
  await review.getByRole('button', { name: 'Kommentera', exact: true }).click();
  await sheet.getByLabel('Din kommentar').fill('Det ser bra ut nu.');
  await sheet.getByRole('button', { name: 'Skicka kommentar', exact: true }).click();
  await expect(sheet.getByText('Det ser bra ut nu.', { exact: true })).toBeVisible();
  await panel.getByRole('button', { name: 'Uppdatera kommentarer' }).click();
  await page.screenshot({ path: output + '/03-owner-editor.png', fullPage: true });

  // An explicit choice is required when signing a source with changes since review.
  const beforeSigning = await saved();
  assert.equal((await api.put(`${baseURL}/api/drafts/${id}`, { headers: { Origin: baseURL }, data: { expectedRevision: beforeSigning.revision, draft: { ...beforeSigning.draft, company: { id: 'client', name: 'Client AB', orgNr: '', address: '', zip: '', city: '', contacts: [{ id: 'anna', name: 'Anna Client', email: 'anna@example.test', role: '', signs: true }] } } } })).status(), 200);
  await page.reload();
  await page.getByRole('button', { name: 'Skicka', exact: true }).click();
  const signingSheet = page.getByRole('dialog', { name: 'Skicka för signering' });
  await signingSheet.getByRole('button', { name: 'Skicka för signering' }).click();
  assert.equal((await (await api.get(baseURL + '/api/documents')).json()).documents.length, 0);
  await signingSheet.getByRole('checkbox').check();
  await signingSheet.getByRole('button', { name: 'Skicka för signering' }).click();
  await expect(page.getByRole('heading', { name: 'Redo att signeras' })).toBeVisible({ timeout: 20000 });
  const signingLink = await page.getByRole('textbox', { name: 'Personlig länk' }).inputValue();
  const documentId = new URL(page.url()).pathname.split('/')[2];
  const pdfBytes = await (await api.get(`${baseURL}/api/documents/${documentId}/pdf?version=original`)).body();
  const pdf = new PDFDocument(pdfBytes), pdfPage = pdf.loadPage(0), pdfText = pdfPage.toStructuredText('');
  assert.match(pdfText.asText(), /Support ingår under hela året/);
  pdfText.destroy(); pdfPage.destroy(); pdf.destroy();
  assert.equal((await saved()).signings[0].documentId, documentId);
  await review.reload();
  await expect(review.getByRole('heading', { name: 'Avtalet är klart för signering' })).toBeVisible();
  await review.goto(signingLink);
  await expect(review.getByRole('button', { name: 'Signera', exact: true })).toBeEnabled({ timeout: 20000 });
  await expect(review.locator('.rd-workspace .rd-pdf-stage')).toBeVisible();
  await review.getByRole('button', { name: /^Kommentarer/ }).click();
  await expect(sheet.getByText('Det ser bra ut nu.', { exact: true })).toBeVisible();
  await sheet.getByLabel('Fråga om dokumentet').fill('Kan vi starta nästa vecka?');
  await sheet.getByRole('button', { name: 'Skicka kommentar' }).click();
  await expect(sheet.getByText('Kan vi starta nästa vecka?', { exact: true })).toBeVisible();
  await sheet.getByRole('button', { name: 'Stäng kommentarer' }).click();
  await review.getByRole('button', { name: 'Förstora sida 1', exact: true }).click();
  const zoom = review.getByRole('dialog', { name: 'Förstorad sida 1' });
  await expect(zoom.getByRole('img')).toBeVisible();
  await zoom.getByRole('button', { name: 'Stäng', exact: true }).click();
  await review.getByRole('button', { name: 'Webbvisning', exact: true }).click();
  await expect(review.locator('.rd-review-paper')).toContainText('Support ingår');
  await review.getByRole('button', { name: 'Visa PDF och signera' }).click();
  await expect(review.getByRole('dialog', { name: 'Signera', exact: true })).toHaveCount(0);
  await review.getByRole('button', { name: 'Signera', exact: true }).click();
  const signature = review.getByRole('dialog', { name: 'Signera', exact: true });
  const bounds = await signature.locator('canvas').boundingBox();
  await review.mouse.move(bounds.x + 25, bounds.y + 60); await review.mouse.down();
  for (let index = 0; index < 16; index++) await review.mouse.move(bounds.x + 25 + index * 12, bounds.y + 60 + Math.sin(index) * 20);
  await review.mouse.up();
  await signature.getByRole('checkbox').check();
  await signature.getByRole('button', { name: 'Signera dokumentet', exact: true }).click();
  await expect(review.getByRole('heading', { name: 'Signerat', exact: true })).toBeVisible({ timeout: 20000 });
  await expect(review.locator('.rd-pdf-stage')).toBeVisible();
  await expect(review.locator('.signed-receipt').getByText('Anna Client', { exact: true })).toBeVisible();
  await expect(review.getByRole('button', { name: 'Ladda ner signerad PDF', exact: true })).toBeVisible();
  await review.screenshot({ path: output + '/04-client-signed.png', fullPage: true });
  await page.goto(`${baseURL}/editor/${id}`);
  await expect(panel.getByText('Det ser bra ut nu.', { exact: true })).toBeVisible();
  await panel.getByRole('button', { name: 'Återkalla', exact: true }).click();
  await review.goto(link);
  await expect(review.getByRole('alert')).toContainText('Granskningslänken är ogiltig');
  assert.deepEqual(errors, []);
  console.log('Document workspace passed: two review rounds, editor comments, mobile discussion sheet/PDF zoom, exact signing PDF, signing comments and document retained after signing. Screenshots: ' + output);
} catch (error) {
  await ownerPage?.screenshot({ path: output + '/failure-owner.png', fullPage: true }).catch(() => {});
  await clientPage?.screenshot({ path: output + '/failure-client.png', fullPage: true }).catch(() => {});
  throw error;
} finally {
  await browser.close();
  await runtime.db.query('DROP SCHEMA "' + schema + '" CASCADE').catch(() => {});
  await runtime.close();
  await new Promise(resolve => server.close(resolve));
}
